import assert from 'node:assert/strict';
import { applyAction, canInputResult, createDemoState, createInitialState, currentGroups, getStatistics, operationGroups, normalizeEvaluationState, personnelOf } from '../app/lib/evaluation.ts';

const admin={admin:true};
const state=createDemoState('2026-10');
const snapshot=JSON.stringify(state);
const historical=state=>JSON.stringify({months:state.months,cases:state.cases,results:state.results,evaluations:state.evaluations,rankings:state.rankings});
const user=state.users[1];
const edit={type:'saveExaminer',user:{...user,name:'수정 심사관',division:'수정 심사과'},groupId:'group-b',responsibilities:[{groupId:'group-a',methodId:'chatgpt'},{groupId:'group-a',methodId:'claude'}]};
const saved=applyAction(state,admin,edit);
assert.equal(saved.users.find(entry=>entry.id===user.id).name,'수정 심사관');
assert.equal(saved.personnel.memberships.find(entry=>entry.userId===user.id).groupId,'group-b');
assert.equal(saved.personnel.assignments.find(entry=>entry.groupId==='group-a'&&entry.methodId==='chatgpt').userId,user.id);
assert.equal(saved.personnel.assignments.filter(entry=>entry.groupId==='group-a'&&entry.methodId==='chatgpt').length,1);
assert.deepEqual(saved.personnel.assignments.filter(entry=>entry.groupId==='group-b'),state.personnel.assignments.filter(entry=>entry.groupId==='group-b'));
assert.equal(historical(saved),historical(state));
assert.equal(JSON.stringify(state),snapshot);
assert.throws(()=>applyAction(state,{userId:user.id},edit),error=>error.status===403);
assert.throws(()=>applyAction(state,admin,{...edit,groupId:'missing'}),/소속 그룹/);
assert.throws(()=>applyAction(state,admin,{...edit,responsibilities:[{groupId:'group-a',methodId:'baseline'}]}),/AI 담당/);
assert.throws(()=>applyAction(state,admin,{...edit,responsibilities:[...edit.responsibilities,edit.responsibilities[0]]}),/중복/);
assert.equal(JSON.stringify(state),snapshot,'Rejected edits must not partially save user metadata or group changes.');
assert.throws(()=>applyAction(state,admin,{...edit,user:{...user,active:false},responsibilities:[{groupId:'group-a',methodId:'chatgpt'}]}),/비활성/);
const inactive=applyAction(state,admin,{...edit,user:{...user,active:false},responsibilities:[{groupId:'group-a',methodId:'claude'}]});
assert.equal(inactive.users.find(entry=>entry.id===user.id).active,false);
assert.equal(inactive.personnel.assignments.find(entry=>entry.groupId==='group-a'&&entry.methodId==='claude').userId,user.id);
const noAi=applyAction(state,admin,{...edit,user:{...user,roles:['examiner']}});
assert(noAi.personnel.assignments.every(entry=>entry.userId!==user.id));
assert.equal(historical(noAi),historical(state));

const timestamp=new Date('2026-10-28T04:00:00Z');
const deleted=applyAction(state,admin,{type:'deleteGroup',groupId:'group-a'},timestamp);
assert.equal(currentGroups(deleted).length,1);
assert.equal(deleted.groups.find(group=>group.id==='group-a').deletedAt,timestamp.toISOString());
assert(deleted.personnel.memberships.every(entry=>entry.groupId!=='group-a'));
assert.deepEqual(deleted.personnel.assignments,state.personnel.assignments,'Existing confirmed-case duties remain usable after group deletion.');
assert.equal(historical(deleted),historical(state));
assert.equal(canInputResult(deleted,{userId:'demo-user-1'},deleted.cases[0],'chatgpt'),true);
assert.equal(operationGroups(deleted,'2026-10').length,2);
assert.equal(getStatistics(deleted,'2026-10').groups.find(group=>group.id==='group-a').cases,10);
assert.equal(getStatistics(deleted,'2026-10').summary.complete,20);
assert.throws(()=>applyAction(deleted,admin,{...edit,groupId:'group-a'}),/소속 그룹/);
assert.throws(()=>applyAction(deleted,admin,{type:'saveGroup',group:{id:'group-a',name:'실수로 복원'}}),/삭제된 그룹/);
assert.throws(()=>applyAction(state,{userId:user.id},{type:'deleteGroup',groupId:'group-a'}),error=>error.status===403);
assert.throws(()=>applyAction(state,admin,{type:'deleteGroup',groupId:'missing'}),error=>error.status===404);
assert.equal(JSON.stringify(applyAction(deleted,admin,{type:'deleteGroup',groupId:'group-a'})),JSON.stringify(deleted));
const reassigned=applyAction(deleted,admin,{...edit,groupId:'group-b'});
assert.equal(canInputResult(reassigned,{userId:user.id},reassigned.cases[0],'chatgpt'),true,'Historical group duties can be reassigned while retaining original case grouping.');
assert.equal(reassigned.cases[0].groupId,'group-a');
let cancelled=deleted;
for(const item of deleted.cases.filter(item=>item.groupId==='group-a')) cancelled=applyAction(cancelled,admin,{type:'cancelCase',caseId:item.id});
assert(cancelled.personnel.assignments.every(entry=>entry.groupId!=='group-a'),'Cancelled historical work must not leave unused archived responsibilities.');
assert.equal(cancelled.results.length,state.results.length);

let empty=createInitialState('2026-10');
empty=applyAction(empty,admin,{type:'saveGroup',group:{id:'empty',name:'미사용 그룹'}});
empty=applyAction(empty,admin,{type:'saveExaminer',user:{name:'신규 심사관',bureau:'기획국',division:'신규과',roles:['examiner','ai'],active:true},groupId:'empty',responsibilities:[{groupId:'empty',methodId:'chatgpt'}]});
assert.equal(empty.users.length,1);
assert.equal(empty.personnel.memberships[0].userId,empty.users[0].id);
assert.equal(empty.personnel.assignments[0].userId,empty.users[0].id);
empty=applyAction(empty,admin,{type:'deleteGroup',groupId:'empty'});
assert.equal(currentGroups(empty).length,2);
assert.equal(personnelOf(empty).memberships.length,0);
assert.equal(personnelOf(empty).assignments.length,0,'Unused assignments do not linger after deletion.');
assert.equal(empty.users.length,1);
assert.equal(operationGroups(empty,'2026-10').length,2);
console.log('Examiner management: atomic profile/group/AI edits, role and inactive guards, reassignment, nondestructive group deletion, historical permissions/statistics and new-user IDs passed.');

const initialGroups = createInitialState();
assert.deepEqual(currentGroups(initialGroups).map(group => group.name), ['그룹 1', '그룹 2']);
const legacyEmptyGroups = { ...initialGroups, groups: [], defaultGroupVersion: undefined };
const backfilledGroups = normalizeEvaluationState(legacyEmptyGroups);
assert.deepEqual(backfilledGroups.groups, initialGroups.groups);
assert.equal(legacyEmptyGroups.groups.length, 0, 'Backfill does not mutate the stored snapshot.');
assert.equal(normalizeEvaluationState(backfilledGroups), backfilledGroups);
const customGroups = { ...legacyEmptyGroups, groups: [{ id: 'custom', name: '기존 사용자 그룹' }] };
assert.deepEqual(normalizeEvaluationState(customGroups).groups, customGroups.groups);
let removedDefaults = backfilledGroups;
for (const group of initialGroups.groups) removedDefaults = applyAction(removedDefaults, admin, { type: 'deleteGroup', groupId: group.id });
assert.equal(currentGroups(normalizeEvaluationState(removedDefaults)).length, 0, 'Do not recreate groups intentionally deleted after initialization.');
