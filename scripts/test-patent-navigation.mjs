import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { applicationNumberLabel, fullTextRequest, normalizeApplicationNumber, SAMPLE_APPLICATION_NUMBER } from '../app/lib/patent-number.ts';
import { patentFeedback } from '../app/lib/patent-feedback.ts';

const require = createRequire(import.meta.url);
assert.equal(normalizeApplicationNumber('10-2020-0093844'), SAMPLE_APPLICATION_NUMBER);
assert.equal(normalizeApplicationNumber(' 10 2020 0093844 '), SAMPLE_APPLICATION_NUMBER);
for (const input of ['', '123', 'ABC1020200093844', '10/2020/0093844', 'KR1020200093844', '3020200093844']) assert.equal(normalizeApplicationNumber(input), null, input);
assert.equal(applicationNumberLabel('123'), '123');
assert.equal(applicationNumberLabel('1020200093844'), '10-2020-0093844');
assert.deepEqual(fullTextRequest('123'), { requested: '123', normalized: null, demo: false });
assert.deepEqual(fullTextRequest(undefined), { requested: '', normalized: null, demo: false });
assert.deepEqual(fullTextRequest('123', true), { requested: '123', normalized: null, demo: false });
assert.deepEqual(fullTextRequest(undefined, true), { requested: SAMPLE_APPLICATION_NUMBER, normalized: SAMPLE_APPLICATION_NUMBER, demo: true });
assert.equal(fullTextRequest(SAMPLE_APPLICATION_NUMBER).demo, false, 'a real application request is not an implicit sample');
assert.equal(patentFeedback(new TypeError('Failed to fetch'), 'case'), '서비스에 연결하지 못했습니다. 인터넷 연결을 확인한 뒤 다시 시도해 주세요.');
assert(patentFeedback(new Error('OpenAI request failed: private diagnostic'), 'summary').includes('AI 요약을 만들지 못했습니다.'));
assert(!patentFeedback(new Error('OpenAI request failed: private diagnostic'), 'summary').includes('OpenAI'));
assert(patentFeedback(new Error('Unexpected token < in JSON'), 'summary-read').includes('저장된 AI 요약을 불러오지 못했습니다.'));
assert(!patentFeedback(new Error('Unexpected token < in JSON'), 'summary-read').includes('만들지 못했습니다'));
assert(!patentFeedback(new Error('https://example.com?accessKey=private-token'), 'notice').includes('private-token'));
assert(patentFeedback(new SyntaxError('Unexpected token < in JSON'), 'fulltext').includes('전문 다시 불러오기'));
assert.equal(patentFeedback(new Error('공개된 전문이 없습니다.'), 'fulltext'), '공개된 전문이 없습니다. 잠시 후 다시 시도해 주세요.');
assert.equal(patentFeedback(new Error('출원번호를 확인해 주세요.'), 'case'), '출원번호를 확인해 주세요.');

// Render the actual invalid/no-input branches, without browser effects or API calls.
let source = await readFile(new URL('../app/fulltext/fulltext-viewer.tsx', import.meta.url), 'utf8');
source = source.replace("import Link from 'next/link';", "import { createElement } from 'react'; const Link = ({ href, children, ...props }) => createElement('a', { href, ...props }, children);");
source = source.replace("import PdfDownloadButton from '../components/pdf-download';", 'const PdfDownloadButton = () => null;');
source = source.replace("from '../lib/patent-number'", `from ${JSON.stringify(new URL('../app/lib/patent-number.ts', import.meta.url).href)}`);
source = source.replace("from '../lib/patent-feedback'", `from ${JSON.stringify(new URL('../app/lib/patent-feedback.ts', import.meta.url).href)}`);
let compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, jsx: ts.JsxEmit.ReactJSX } }).outputText;
compiled = compiled.replaceAll('from "react/jsx-runtime"', `from ${JSON.stringify(pathToFileURL(require.resolve('react/jsx-runtime')).href)}`).replaceAll("from 'react'", `from ${JSON.stringify(pathToFileURL(require.resolve('react')).href)}`);
const { default: FullTextViewer } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
const invalid = renderToStaticMarkup(React.createElement(FullTextViewer, { initialApplicationNumber: '123' }));
assert(invalid.includes('출원번호를 확인해 주세요.'));
assert(invalid.includes('입력한 번호:'));
assert(invalid.includes('123'));
assert(!invalid.includes(SAMPLE_APPLICATION_NUMBER), 'invalid input must not link to or display a different sample application');
assert(!invalid.includes('샘플 사건'));
const empty = renderToStaticMarkup(React.createElement(FullTextViewer, { initialApplicationNumber: '' }));
assert(empty.includes('출원번호로 전문을 조회하세요.'));
assert(empty.includes('샘플 전문 보기'), 'sample requires an explicit user action');
const requested = renderToStaticMarkup(React.createElement(FullTextViewer, { initialApplicationNumber: '10-2020-0093844' }));
assert(requested.includes('10-2020-0093844'));
assert(requested.includes('명세서와 청구항을 불러오는 중입니다.'));
assert(!requested.includes('샘플 사건'));
console.log('Patent navigation tests passed: strict number parsing, original input preservation, explicit sample requests, actual invalid/empty/requested screen branches.');
